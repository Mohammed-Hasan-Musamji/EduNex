"""Assessment question and attempt schemas.

QuestionPublic deliberately omits the correct answer and explanation so the
frontend cannot read them before a learner submits an attempt.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from pydantic import BaseModel, Field

from app.models.assessment import QuestionType
from app.models.topic import DifficultyLevel
from app.schemas.common import ORMModel
from app.schemas.gamification import RewardSummary


class QuestionPublic(ORMModel):
    id: uuid.UUID
    topic_id: uuid.UUID
    question_text: str
    question_type: QuestionType
    options: list[str] | None
    difficulty: DifficultyLevel
    # Learner-visible questions are Gemini-generated or admin-authored, never seeded examples.
    origin: str
    review_status: str = "approved"
    source_title: str | None = None
    source_page: int | None = None


class PracticeQuestionGenerationResult(BaseModel):
    topic_id: uuid.UUID
    accepted: int
    rejected_invalid: int
    rejected_duplicate: int


class AttemptCreate(BaseModel):
    """learner_id is intentionally absent -- the route derives it from the
    authenticated session, never from client input."""

    question_id: uuid.UUID
    # Multiple-choice: option index. True/false: boolean. Validated against
    # the question's actual type on the server in assessment_service.
    submitted_answer: int | bool = Field(description="Option index for multiple_choice, boolean for true_false")


class AttemptResult(BaseModel):
    attempt_id: uuid.UUID
    question_id: uuid.UUID
    is_correct: bool
    score: float
    feedback: str
    explanation: str
    created_at: datetime


class AttemptRead(ORMModel):
    id: uuid.UUID
    learner_id: uuid.UUID
    question_id: uuid.UUID
    submitted_answer: int | bool
    is_correct: bool
    score: float
    feedback: str
    created_at: datetime


class RoundAnswer(BaseModel):
    question_id: uuid.UUID
    submitted_answer: int | bool


class PracticeRoundCreate(BaseModel):
    """One practice round submitted as a unit. `client_request_id` is an
    idempotency key generated by the client per attempt at submitting -- a
    retried request with the same key returns the stored result instead of
    recording (and rewarding) the round twice."""

    topic_id: uuid.UUID
    client_request_id: str = Field(min_length=8, max_length=64, pattern=r"^[A-Za-z0-9_-]+$")
    answers: list[RoundAnswer] = Field(min_length=1, max_length=50)


class RoundQuestionResult(BaseModel):
    question_id: uuid.UUID
    is_correct: bool
    explanation: str
    difficulty: DifficultyLevel


class PracticeRoundResult(BaseModel):
    round_id: uuid.UUID
    topic_id: uuid.UUID
    topic_name: str
    correct: int
    total: int
    score: float
    previous_score: float | None
    results: list[RoundQuestionResult]
    completed_at: datetime
    replayed: bool
    rewards: RewardSummary | None
